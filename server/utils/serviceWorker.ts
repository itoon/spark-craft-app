import { createHash } from "node:crypto";
import { readdir } from "node:fs/promises";
import { join, relative, sep } from "node:path";

/**
 * Offline support for shared apps (/pwa/<id>), served as /sw.js.
 *
 * - every file of the build (/_nuxt/…) is downloaded when the worker installs,
 *   so the app opens with no network — even parts that weren't on screen yet
 * - the page shell (same HTML for every route, ssr: false) is cached too
 * - app data (/api/export/link/<id>) and its manifest + icon: network first, so
 *   a teacher's update arrives whenever the phone is online, cache when offline
 *
 * The cache name carries a hash of the build's file list: a new build gets a
 * fresh cache and the old one is deleted.
 */

export const DATA_CACHE = "codecraft-data";

/** Paths under /_nuxt of a production build's public folder. */
export async function listBuildAssets(publicDir: string): Promise<string[]> {
  const root = join(publicDir, "_nuxt");
  try {
    const entries = await readdir(root, { recursive: true, withFileTypes: true });
    return entries
      .filter((entry) => entry.isFile())
      .map((entry) => `/_nuxt/${relative(root, join(entry.parentPath, entry.name)).split(sep).join("/")}`)
      .filter((path) => !path.endsWith(".map"))
      .sort();
  } catch {
    return []; // `bun run dev` — no build; the page doesn't register the worker there
  }
}

export function buildServiceWorker(assets: string[]): string {
  const version = createHash("sha256").update(assets.join("\n")).digest("hex").slice(0, 12);
  return `// CodeCraft offline worker — generated by server/utils/serviceWorker.ts
const SHELL_CACHE = "codecraft-shell-${version}";
const DATA_CACHE = ${JSON.stringify(DATA_CACHE)};
const SHELL = "/";
const ASSETS = ${JSON.stringify(assets)};

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(SHELL_CACHE);
    // all or nothing: a half-cached app would break offline later, so fail and retry next visit
    await cache.addAll([new Request(SHELL, { cache: "reload" }), ...ASSETS]);
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith("codecraft-shell-") && key !== SHELL_CACHE) await caches.delete(key);
    }
    await self.clients.claim();
  })());
});

async function networkFirst(request, cacheName, fallbackKey) {
  const cache = await caches.open(cacheName);
  try {
    const response = await fetch(request);
    if (response.ok) await cache.put(fallbackKey || request, response.clone());
    return response;
  } catch (error) {
    const cached = await cache.match(fallbackKey || request);
    if (cached) return cached;
    throw error;
  }
}

async function cacheFirst(request) {
  const cached = await caches.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) (await caches.open(SHELL_CACHE)).put(request, response.clone());
  return response;
}

self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return; // map tiles etc. need the internet anyway

  if (request.mode === "navigate") {
    // Same HTML for every page: refresh the cached shell when online
    event.respondWith(networkFirst(request, SHELL_CACHE, SHELL));
  } else if (url.pathname.startsWith("/_nuxt/") || url.pathname.startsWith("/api/_nuxt_icon/")) {
    event.respondWith(cacheFirst(request));
  } else if (url.pathname.startsWith("/api/export/link/") || url.pathname.startsWith("/api/pwa/")) {
    event.respondWith(networkFirst(request, DATA_CACHE));
  }
});
`;
}
