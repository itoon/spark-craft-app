function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48) || "codecraft-ionic-app";
}

function pascalCase(value: string): string {
  return value
    .replace(/(^\w|[\s_-]+\w)/g, (part) => part.replace(/[\s_-]+/, "").toUpperCase())
    .replace(/[^A-Za-z0-9]/g, "") || "CodeCraftApp";
}

function varNameFromId(id: string): string {
  const parts = id.split("_");
  return parts[parts.length - 1] ?? id;
}

export function buildDefaultPageCode(pageElements: AppElement[]): string {
  const rootElements = pageElements.filter((element) => element.parentId === null);

  if (rootElements.length === 0) {
    return [
      "// No elements on this page yet.",
      "// Add components in Design mode to export a usable screen.",
    ].join("\n");
  }

  const orderedRoots = [
    ...rootElements.filter((element) => element.type === "Toolbar"),
    ...rootElements.filter((element) => element.type !== "Toolbar" && element.type !== "Container"),
  ];

  const lines: string[] = ["// Generated by CodeCraft for Ionic Vue", ""];

  for (const element of orderedRoots) {
    const className = ELEMENT_CLASS_MAP[element.type] ?? element.type;
    const variableName = varNameFromId(element.id);
    lines.push(`const ${variableName} = new ${className}('${element.id}')`);
    lines.push(`page.add(${variableName})`);
    lines.push("");
  }

  const lastButton = [...orderedRoots].reverse().find((element) => element.type === "Button");
  if (lastButton) {
    const variableName = varNameFromId(lastButton.id);
    lines.push("// Example interaction");
    lines.push(`${variableName}.onClick(() => {`);
    lines.push(`  console.log('${variableName} clicked')`);
    lines.push("})");
  }

  return lines.join("\n").trim();
}

